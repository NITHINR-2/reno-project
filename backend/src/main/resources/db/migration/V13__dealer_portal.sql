-- Dealer Portal (Phase D1): DEALER role, dealer-bound users, set-password links, dealer orders,
-- catalogue fields on vehicle models and payment-proof uploads.

ALTER TABLE roles DROP CONSTRAINT ck_roles_code;
ALTER TABLE roles ADD CONSTRAINT ck_roles_code
    CHECK (code IN ('ADMIN', 'SUPERVISOR', 'MARKETING_MANAGER', 'MARKETING_HEAD', 'FINANCE_TEAM', 'DEALER'));

INSERT INTO roles (code, name, description) VALUES
    ('DEALER', 'Dealer', 'Dealer Portal only: catalogue, own orders, own quotations and payment proofs.');

INSERT INTO permissions (code, description) VALUES
    ('DEALER_PORTAL',    'Use the Dealer Portal for the user''s own dealership'),
    ('CATALOGUE_MANAGE', 'Create and edit catalogue models and variants');

-- DEALER_PORTAL is DEALER-only: the portal is scoped to users.dealer_id, which HQ users (SUPERVISOR included) lack.
INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id FROM roles r JOIN permissions p ON p.code = 'DEALER_PORTAL' WHERE r.code = 'DEALER';
INSERT INTO role_permissions (role_id, permission_id)
SELECT r.id, p.id FROM roles r JOIN permissions p ON p.code = 'CATALOGUE_MANAGE' WHERE r.code IN ('ADMIN', 'SUPERVISOR');

-- A DEALER user belongs to exactly one dealership (enforced by UserAdminService; null = no portal data).
ALTER TABLE users ADD COLUMN dealer_id BIGINT REFERENCES dealers (id);
CREATE INDEX ix_users_dealer ON users (dealer_id);

-- Setting a password through a link signs the user out everywhere.
ALTER TABLE refresh_tokens DROP CONSTRAINT ck_refresh_tokens_revoke_reason;
ALTER TABLE refresh_tokens ADD CONSTRAINT ck_refresh_tokens_revoke_reason CHECK (
    revoke_reason IS NULL OR revoke_reason IN ('LOGOUT', 'REUSE_DETECTED', 'ADMIN', 'USER_DEACTIVATED', 'PASSWORD_CHANGED'));

-- One-time set-password links. Only the SHA-256 of the token is stored; a link is spent by setting used_at.
CREATE TABLE set_password_tokens (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash    VARCHAR(64) NOT NULL,
    expires_at    TIMESTAMPTZ NOT NULL,
    used_at       TIMESTAMPTZ,
    revoked_at    TIMESTAMPTZ,
    created_by_id BIGINT      NOT NULL REFERENCES users (id),
    created_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    version       BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT uq_set_password_tokens_hash UNIQUE (token_hash),
    CONSTRAINT ck_set_password_tokens_hash CHECK (token_hash ~ '^[0-9a-f]{64}$'),
    CONSTRAINT ck_set_password_tokens_expiry CHECK (expires_at > created_at),
    CONSTRAINT ck_set_password_tokens_spent CHECK (used_at IS NULL OR revoked_at IS NULL)
);
CREATE INDEX ix_set_password_tokens_user ON set_password_tokens (user_id);
CREATE INDEX ix_set_password_tokens_created_by ON set_password_tokens (created_by_id);

-- Catalogue presentation fields (the dealer catalogue lists active models with active variants only).
ALTER TABLE vehicle_models
    ADD COLUMN description      VARCHAR(1000),
    ADD COLUMN body_type        VARCHAR(20),
    ADD COLUMN seating_capacity INTEGER,
    ADD COLUMN image_url        VARCHAR(500),
    ADD CONSTRAINT ck_vehicle_models_body_type CHECK (
        body_type IS NULL OR body_type IN ('HATCHBACK', 'SEDAN', 'SUV', 'COMPACT_SUV', 'MPV', 'VAN', 'PICKUP')),
    ADD CONSTRAINT ck_vehicle_models_seating CHECK (seating_capacity IS NULL OR seating_capacity BETWEEN 1 AND 60),
    ADD CONSTRAINT ck_vehicle_models_image_url CHECK (image_url IS NULL OR image_url ~ '^https://\S+$');

-- A dealer's order: one fleet request per line, so each line runs through the HQ workflow on its own.
CREATE SEQUENCE dealer_order_number_seq START WITH 1000;

CREATE TABLE dealer_orders (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_number            VARCHAR(20)  NOT NULL,
    dealer_id               BIGINT       NOT NULL REFERENCES dealers (id),
    created_by_id           BIGINT       NOT NULL REFERENCES users (id),
    requested_delivery_date DATE,
    notes                   VARCHAR(2000),
    created_at              TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at              TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version                 BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uq_dealer_orders_number UNIQUE (order_number),
    CONSTRAINT ck_dealer_orders_number CHECK (order_number ~ '^DO-[0-9]{4}-[0-9]{4,}$')
);
CREATE INDEX ix_dealer_orders_dealer_created ON dealer_orders (dealer_id, created_at DESC);
CREATE INDEX ix_dealer_orders_created_by ON dealer_orders (created_by_id);

ALTER TABLE fleet_requests
    ADD COLUMN dealer_order_id      BIGINT REFERENCES dealer_orders (id),
    ADD COLUMN dealer_order_line_no INTEGER,
    ADD CONSTRAINT ck_fleet_requests_dealer_order_line CHECK (
        (dealer_order_id IS NULL AND dealer_order_line_no IS NULL)
        OR (dealer_order_id IS NOT NULL AND dealer_order_line_no > 0)),
    ADD CONSTRAINT uq_fleet_requests_dealer_order_line UNIQUE (dealer_order_id, dealer_order_line_no);

-- Proof of payment uploaded by a dealer; one file per (pending) receipt. Bytes stay in the database (max 5 MB).
CREATE TABLE payment_proofs (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_receipt_id BIGINT       NOT NULL REFERENCES payment_receipts (id),
    file_name          VARCHAR(255) NOT NULL,
    content_type       VARCHAR(50)  NOT NULL,
    size_bytes         INTEGER      NOT NULL,
    sha256             VARCHAR(64)  NOT NULL,
    content            BYTEA        NOT NULL,
    uploaded_by_id     BIGINT       NOT NULL REFERENCES users (id),
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version            BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uq_payment_proofs_receipt UNIQUE (payment_receipt_id),
    CONSTRAINT ck_payment_proofs_type CHECK (content_type IN ('application/pdf', 'image/png', 'image/jpeg')),
    CONSTRAINT ck_payment_proofs_size CHECK (size_bytes BETWEEN 1 AND 5242880 AND size_bytes = octet_length(content)),
    CONSTRAINT ck_payment_proofs_sha256 CHECK (sha256 ~ '^[0-9a-f]{64}$')
);
CREATE INDEX ix_payment_proofs_uploaded_by ON payment_proofs (uploaded_by_id);
