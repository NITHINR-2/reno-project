-- Append-only history: workflow transitions and the audit trail. Rows are never updated or deleted.

CREATE TABLE workflow_history (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fleet_request_id BIGINT       NOT NULL REFERENCES fleet_requests (id),
    from_status      VARCHAR(40),
    to_status        VARCHAR(40),
    action           VARCHAR(40)  NOT NULL,
    actor_id         BIGINT       REFERENCES users (id),
    actor_role       VARCHAR(40),
    reason           VARCHAR(1000),
    is_override      BOOLEAN      NOT NULL DEFAULT FALSE,
    metadata         JSONB,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_workflow_history_override_reason CHECK (NOT is_override OR reason IS NOT NULL),
    -- actor_id is NULL only for system events (e.g. SLA_BREACHED from the scheduler).
    CONSTRAINT ck_workflow_history_actor CHECK (actor_id IS NOT NULL OR actor_role IS NULL)
);
CREATE INDEX ix_workflow_history_request ON workflow_history (fleet_request_id, created_at);
CREATE INDEX ix_workflow_history_actor ON workflow_history (actor_id);
CREATE INDEX ix_workflow_history_action ON workflow_history (action);

CREATE TABLE audit_logs (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id       BIGINT       REFERENCES users (id),
    actor_username VARCHAR(60),
    actor_role     VARCHAR(40),
    action         VARCHAR(60)  NOT NULL,
    entity_type    VARCHAR(60)  NOT NULL,
    entity_id      VARCHAR(60),
    before_json    JSONB,
    after_json     JSONB,
    reason         VARCHAR(1000),
    ip_address     VARCHAR(45),
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX ix_audit_logs_entity ON audit_logs (entity_type, entity_id);
CREATE INDEX ix_audit_logs_actor ON audit_logs (actor_id);
CREATE INDEX ix_audit_logs_created_at ON audit_logs (created_at);
CREATE INDEX ix_audit_logs_action ON audit_logs (action);

CREATE FUNCTION reject_append_only_change() RETURNS trigger
    LANGUAGE plpgsql AS
$$
BEGIN
    RAISE EXCEPTION '% is append-only; % is not allowed', TG_TABLE_NAME, TG_OP
        USING ERRCODE = 'restrict_violation';
END;
$$;

CREATE TRIGGER trg_workflow_history_append_only
    BEFORE UPDATE OR DELETE ON workflow_history
    FOR EACH ROW EXECUTE FUNCTION reject_append_only_change();

CREATE TRIGGER trg_audit_logs_append_only
    BEFORE UPDATE OR DELETE ON audit_logs
    FOR EACH ROW EXECUTE FUNCTION reject_append_only_change();
