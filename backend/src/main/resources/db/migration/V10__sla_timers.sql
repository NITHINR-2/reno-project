-- The clock is frozen when a stage is entered: later policy edits apply to stages entered afterwards.
ALTER TABLE fleet_requests
    ADD COLUMN stage_entered_at TIMESTAMPTZ,
    ADD COLUMN sla_warning_at   TIMESTAMPTZ,
    ADD COLUMN sla_due_at       TIMESTAMPTZ,
    ADD COLUMN sla_breached_at  TIMESTAMPTZ,
    ADD CONSTRAINT ck_fleet_requests_sla CHECK (
        (sla_due_at IS NULL AND sla_warning_at IS NULL AND sla_breached_at IS NULL)
        OR (stage_entered_at IS NOT NULL AND sla_warning_at IS NOT NULL
            AND stage_entered_at <= sla_warning_at AND sla_warning_at <= sla_due_at));

-- Backfill: the stage started at the last history row that moved the request into its current status.
UPDATE fleet_requests r
SET stage_entered_at = COALESCE(
        (SELECT max(h.created_at) FROM workflow_history h
         WHERE h.fleet_request_id = r.id AND h.to_status = r.status AND h.from_status IS DISTINCT FROM h.to_status),
        r.updated_at)
WHERE r.status NOT IN ('COMPLETED', 'CANCELLED');

UPDATE fleet_requests r
SET sla_due_at     = r.stage_entered_at + make_interval(hours => p.hours_allowed),
    sla_warning_at = r.stage_entered_at + make_interval(mins => p.hours_allowed * 60 * p.warning_threshold_pct / 100)
FROM sla_policies p
WHERE p.stage = r.status AND p.active AND r.stage_entered_at IS NOT NULL;

-- The breach scan looks for due, unrecorded clocks.
CREATE INDEX ix_fleet_requests_sla_open ON fleet_requests (sla_due_at) WHERE sla_breached_at IS NULL;
CREATE INDEX ix_fleet_requests_sla_due ON fleet_requests (sla_due_at);

-- Last line of defence: one SLA_BREACHED event per request per stage entry, even with concurrent scanners.
CREATE UNIQUE INDEX ux_workflow_history_sla_breach
    ON workflow_history (fleet_request_id, (metadata ->> 'stageEnteredAt'))
    WHERE action = 'SLA_BREACHED';
