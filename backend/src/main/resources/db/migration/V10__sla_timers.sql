-- SLA timers: one policy per timed workflow stage, and the stage clock on each request.
-- Hours are calendar hours (Asia/Kolkata has no DST, so an instant + N hours is N IST hours).

CREATE TABLE sla_policies (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    stage                 VARCHAR(40) NOT NULL,
    hours_allowed         INTEGER     NOT NULL,
    warning_threshold_pct INTEGER     NOT NULL DEFAULT 75,
    active                BOOLEAN     NOT NULL DEFAULT TRUE,
    created_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT now(),
    version               BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT uk_sla_policies_stage UNIQUE (stage),
    -- Terminal states never have an SLA.
    CONSTRAINT ck_sla_policies_stage CHECK (stage IN (
        'PENDING_MARKETING_REVIEW', 'MARKETING_QUALIFIED', 'PENDING_EXECUTIVE_APPROVAL', 'EXECUTIVE_APPROVED',
        'RETURNED_TO_MARKETING', 'PENDING_FINANCE_CLEARANCE', 'QUOTATION_ISSUED', 'PAYMENT_PENDING',
        'FUNDS_VERIFIED', 'FINANCIALLY_CLEARED', 'PRODUCTION_SCHEDULED', 'DISPATCH_SCHEDULED')),
    CONSTRAINT ck_sla_policies_hours CHECK (hours_allowed BETWEEN 1 AND 8760),
    CONSTRAINT ck_sla_policies_warning CHECK (warning_threshold_pct BETWEEN 1 AND 99)
);

