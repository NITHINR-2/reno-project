-- Master data: regions, dealers, plants, vehicle catalogue, inventory, tax rates.

-- Trusted extension (PG13+): lets the database owner build the non-overlap EXCLUDE constraint on tax_rates.
CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE TABLE regions (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(30)  NOT NULL,
    name       VARCHAR(100) NOT NULL,
    active     BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version    BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uq_regions_code UNIQUE (code),
    CONSTRAINT uq_regions_name UNIQUE (name)
);

CREATE TABLE dealers (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dealer_code   VARCHAR(30)  NOT NULL,
    name          VARCHAR(150) NOT NULL,
    region_id     BIGINT       NOT NULL REFERENCES regions (id),
    gstin         VARCHAR(15),
    contact_name  VARCHAR(150),
    contact_email VARCHAR(255),
    contact_phone VARCHAR(20),
    address_line  VARCHAR(255),
    city          VARCHAR(100) NOT NULL,
    state         VARCHAR(100) NOT NULL,
    postal_code   VARCHAR(10),
    status        VARCHAR(30)  NOT NULL DEFAULT 'PENDING_ONBOARDING',
    onboarded_at  TIMESTAMPTZ,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version       BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uq_dealers_code UNIQUE (dealer_code),
    CONSTRAINT uq_dealers_gstin UNIQUE (gstin),
    -- GSTIN: 2-digit state code, 10-char PAN, entity number, 'Z', checksum.
    CONSTRAINT ck_dealers_gstin CHECK (gstin IS NULL OR gstin ~ '^[0-9]{2}[A-Z]{5}[0-9]{4}[A-Z][1-9A-Z]Z[0-9A-Z]$'),
    CONSTRAINT ck_dealers_status CHECK (status IN ('PENDING_ONBOARDING', 'ACTIVE', 'SUSPENDED')),
    CONSTRAINT ck_dealers_onboarded CHECK (status = 'PENDING_ONBOARDING' OR onboarded_at IS NOT NULL)
);
CREATE INDEX ix_dealers_region ON dealers (region_id);
CREATE INDEX ix_dealers_status ON dealers (status);

CREATE TABLE plants (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code       VARCHAR(30)  NOT NULL,
    name       VARCHAR(100) NOT NULL,
    city       VARCHAR(100) NOT NULL,
    state      VARCHAR(100) NOT NULL,
    active     BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version    BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uq_plants_code UNIQUE (code)
);

CREATE TABLE vehicle_models (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code             VARCHAR(30)  NOT NULL,
    name             VARCHAR(100) NOT NULL,
    vehicle_category VARCHAR(40)  NOT NULL,
    active           BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version          BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uq_vehicle_models_code UNIQUE (code),
    CONSTRAINT ck_vehicle_models_category CHECK (vehicle_category ~ '^[A-Z][A-Z0-9_]*$')
);
CREATE INDEX ix_vehicle_models_category ON vehicle_models (vehicle_category);

CREATE TABLE vehicle_variants (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_id   BIGINT        NOT NULL REFERENCES vehicle_models (id),
    code       VARCHAR(40)   NOT NULL,
    name       VARCHAR(100)  NOT NULL,
    fuel_type  VARCHAR(20)   NOT NULL,
    unit_price NUMERIC(15, 2) NOT NULL,
    active     BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ   NOT NULL DEFAULT now(),
    version    BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT uq_vehicle_variants_code UNIQUE (code),
    CONSTRAINT ck_vehicle_variants_price CHECK (unit_price > 0),
    CONSTRAINT ck_vehicle_variants_fuel CHECK (fuel_type IN ('PETROL', 'DIESEL', 'CNG', 'HYBRID', 'ELECTRIC'))
);
CREATE INDEX ix_vehicle_variants_model ON vehicle_variants (model_id);

CREATE TABLE inventory_locations (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          VARCHAR(30)  NOT NULL,
    name          VARCHAR(100) NOT NULL,
    location_type VARCHAR(20)  NOT NULL,
    region_id     BIGINT REFERENCES regions (id),
    plant_id      BIGINT REFERENCES plants (id),
    active        BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version       BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uq_inventory_locations_code UNIQUE (code),
    CONSTRAINT ck_inventory_locations_type CHECK (location_type IN ('YARD', 'PLANT', 'WAREHOUSE')),
    CONSTRAINT ck_inventory_locations_plant CHECK (location_type <> 'PLANT' OR plant_id IS NOT NULL)
);
CREATE INDEX ix_inventory_locations_region ON inventory_locations (region_id);
CREATE INDEX ix_inventory_locations_plant ON inventory_locations (plant_id);

-- Stock rows are locked with SELECT ... FOR UPDATE during allocation; the CHECKs are the last line of defence.
CREATE TABLE inventory_stock (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location_id        BIGINT      NOT NULL REFERENCES inventory_locations (id),
    variant_id         BIGINT      NOT NULL REFERENCES vehicle_variants (id),
    quantity_available INTEGER     NOT NULL DEFAULT 0,
    quantity_allocated INTEGER     NOT NULL DEFAULT 0,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ NOT NULL DEFAULT now(),
    version            BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT uq_inventory_stock_location_variant UNIQUE (location_id, variant_id),
    CONSTRAINT ck_inventory_stock_available CHECK (quantity_available >= 0),
    CONSTRAINT ck_inventory_stock_allocated CHECK (quantity_allocated >= 0)
);
CREATE INDEX ix_inventory_stock_variant ON inventory_stock (variant_id);

-- GST rates per vehicle category, effective-dated. effective_to is exclusive; NULL means open-ended.
CREATE TABLE tax_rates (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_category VARCHAR(40)  NOT NULL,
    tax_type         VARCHAR(10)  NOT NULL DEFAULT 'GST',
    rate             NUMERIC(5, 4) NOT NULL,
    effective_from   DATE         NOT NULL,
    effective_to     DATE,
    notes            VARCHAR(500),
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version          BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT ck_tax_rates_rate CHECK (rate >= 0 AND rate < 1),
    CONSTRAINT ck_tax_rates_type CHECK (tax_type IN ('GST')),
    CONSTRAINT ck_tax_rates_period CHECK (effective_to IS NULL OR effective_to > effective_from),
    CONSTRAINT ex_tax_rates_no_overlap EXCLUDE USING gist (
        vehicle_category WITH =,
        tax_type WITH =,
        daterange(effective_from, effective_to, '[)') WITH &&)
);
CREATE INDEX ix_tax_rates_category_from ON tax_rates (vehicle_category, effective_from);
