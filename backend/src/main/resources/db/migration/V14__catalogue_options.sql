-- Dealer Portal catalogue options (Phase D2): transmission per variant, colours per model, colour per request.

ALTER TABLE vehicle_variants
    ADD COLUMN transmission VARCHAR(20) NOT NULL DEFAULT 'MANUAL',
    ADD CONSTRAINT ck_vehicle_variants_transmission CHECK (transmission IN ('MANUAL', 'AUTOMATIC', 'AMT', 'CVT', 'DCT'));

CREATE TABLE vehicle_model_colours (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    model_id   BIGINT      NOT NULL REFERENCES vehicle_models (id),
    name       VARCHAR(50) NOT NULL,
    hex_code   VARCHAR(7)  NOT NULL,
    active     BOOLEAN     NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    version    BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT ck_vehicle_model_colours_name CHECK (length(trim(name)) > 0),
    CONSTRAINT ck_vehicle_model_colours_hex CHECK (hex_code ~ '^#[0-9A-F]{6}$')
);
CREATE UNIQUE INDEX ux_vehicle_model_colours_name ON vehicle_model_colours (model_id, lower(name));

-- The colour name is copied onto the request when ordered, so a later catalogue edit can't change an order.
ALTER TABLE fleet_requests ADD COLUMN colour VARCHAR(50);
