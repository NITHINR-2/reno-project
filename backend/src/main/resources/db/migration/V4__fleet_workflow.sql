-- Fleet flow: requests, stock allocations, quotations, payments, production, dispatch.

CREATE TABLE fleet_requests (
    id                        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_number            VARCHAR(20)    NOT NULL,
    dealer_id                 BIGINT         NOT NULL REFERENCES dealers (id),
    variant_id                BIGINT         NOT NULL REFERENCES vehicle_variants (id),
    plant_id                  BIGINT         REFERENCES plants (id),
    quantity                  INTEGER        NOT NULL,
    allocated_qty             INTEGER        NOT NULL DEFAULT 0,
    production_required       INTEGER        NOT NULL DEFAULT 0,
    required_deposit          NUMERIC(15, 2) NOT NULL DEFAULT 0,
    production_estimate_weeks INTEGER,
    requested_delivery_date   DATE,
    status                    VARCHAR(40)    NOT NULL DEFAULT 'PENDING_MARKETING_REVIEW',
    notes                     TEXT,
    return_reason             VARCHAR(1000),
    cancel_reason             VARCHAR(1000),
    created_by_id             BIGINT         NOT NULL REFERENCES users (id),
    assigned_to_id            BIGINT         REFERENCES users (id),
    created_at                TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at                TIMESTAMPTZ    NOT NULL DEFAULT now(),
    version                   BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT uq_fleet_requests_number UNIQUE (request_number),
    CONSTRAINT ck_fleet_requests_number CHECK (request_number ~ '^FLT-[0-9]{4}-[0-9]{4,}$'),
    CONSTRAINT ck_fleet_requests_quantity CHECK (quantity > 0),
    CONSTRAINT ck_fleet_requests_allocated CHECK (allocated_qty >= 0 AND allocated_qty <= quantity),
    CONSTRAINT ck_fleet_requests_production CHECK (production_required >= 0 AND production_required <= quantity),
    CONSTRAINT ck_fleet_requests_deposit CHECK (required_deposit >= 0),
    CONSTRAINT ck_fleet_requests_estimate CHECK (production_estimate_weeks IS NULL OR production_estimate_weeks >= 0),
    CONSTRAINT ck_fleet_requests_status CHECK (status IN (
        'PENDING_MARKETING_REVIEW', 'MARKETING_QUALIFIED', 'PENDING_EXECUTIVE_APPROVAL', 'EXECUTIVE_APPROVED',
        'RETURNED_TO_MARKETING', 'PENDING_FINANCE_CLEARANCE', 'QUOTATION_ISSUED', 'PAYMENT_PENDING',
        'FUNDS_VERIFIED', 'FINANCIALLY_CLEARED', 'PRODUCTION_SCHEDULED', 'DISPATCH_SCHEDULED',
        'COMPLETED', 'CANCELLED')),
    CONSTRAINT ck_fleet_requests_cancel_reason CHECK (status <> 'CANCELLED' OR cancel_reason IS NOT NULL),
    CONSTRAINT ck_fleet_requests_return_reason CHECK (status <> 'RETURNED_TO_MARKETING' OR return_reason IS NOT NULL)
);
CREATE INDEX ix_fleet_requests_status ON fleet_requests (status);
CREATE INDEX ix_fleet_requests_dealer ON fleet_requests (dealer_id);
CREATE INDEX ix_fleet_requests_variant ON fleet_requests (variant_id);
CREATE INDEX ix_fleet_requests_plant ON fleet_requests (plant_id);
CREATE INDEX ix_fleet_requests_created_by ON fleet_requests (created_by_id);
CREATE INDEX ix_fleet_requests_assigned_to ON fleet_requests (assigned_to_id);
CREATE INDEX ix_fleet_requests_created_at ON fleet_requests (created_at);

CREATE TABLE stock_allocations (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fleet_request_id BIGINT      NOT NULL REFERENCES fleet_requests (id),
    stock_id         BIGINT      NOT NULL REFERENCES inventory_stock (id),
    quantity         INTEGER     NOT NULL,
    status           VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    allocated_by_id  BIGINT      NOT NULL REFERENCES users (id),
    released_at      TIMESTAMPTZ,
    created_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ NOT NULL DEFAULT now(),
    version          BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT ck_stock_allocations_quantity CHECK (quantity > 0),
    CONSTRAINT ck_stock_allocations_status CHECK (status IN ('ACTIVE', 'RELEASED', 'CONSUMED')),
    CONSTRAINT ck_stock_allocations_released CHECK (status <> 'RELEASED' OR released_at IS NOT NULL)
);
CREATE UNIQUE INDEX ux_stock_allocations_active ON stock_allocations (fleet_request_id, stock_id) WHERE status = 'ACTIVE';
CREATE INDEX ix_stock_allocations_request ON stock_allocations (fleet_request_id);
CREATE INDEX ix_stock_allocations_stock ON stock_allocations (stock_id);
CREATE INDEX ix_stock_allocations_allocated_by ON stock_allocations (allocated_by_id);

-- Quotation document status is separate from payment status so "one ISSUED per request" stays literal.
CREATE TABLE quotations (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quotation_number  VARCHAR(30)    NOT NULL,
    fleet_request_id  BIGINT         NOT NULL REFERENCES fleet_requests (id),
    status            VARCHAR(20)    NOT NULL DEFAULT 'DRAFT',
    payment_status    VARCHAR(20)    NOT NULL DEFAULT 'UNPAID',
    tax_rate_id       BIGINT         NOT NULL REFERENCES tax_rates (id),
    gst_rate          NUMERIC(5, 4)  NOT NULL,
    base_amount       NUMERIC(15, 2) NOT NULL,
    gst_amount        NUMERIC(15, 2) NOT NULL,
    total_amount      NUMERIC(15, 2) NOT NULL,
    required_deposit  NUMERIC(15, 2) NOT NULL DEFAULT 0,
    deposit_received  NUMERIC(15, 2) NOT NULL DEFAULT 0,
    deposit_shortfall NUMERIC(15, 2) NOT NULL DEFAULT 0,
    currency          VARCHAR(3)     NOT NULL DEFAULT 'INR',
    issue_date        DATE,
    valid_until       DATE,
    issued_at         TIMESTAMPTZ,
    issued_by_id      BIGINT         REFERENCES users (id),
    created_by_id     BIGINT         NOT NULL REFERENCES users (id),
    terms_text        TEXT,
    created_at        TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ    NOT NULL DEFAULT now(),
    version           BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT uq_quotations_number UNIQUE (quotation_number),
    CONSTRAINT ck_quotations_status CHECK (status IN ('DRAFT', 'ISSUED', 'SUPERSEDED', 'CANCELLED')),
    CONSTRAINT ck_quotations_payment_status CHECK (payment_status IN ('UNPAID', 'PARTIALLY_PAID', 'PAID')),
    CONSTRAINT ck_quotations_gst_rate CHECK (gst_rate >= 0 AND gst_rate < 1),
    CONSTRAINT ck_quotations_amounts CHECK (base_amount >= 0 AND gst_amount >= 0 AND total_amount >= 0),
    CONSTRAINT ck_quotations_total CHECK (total_amount = base_amount + gst_amount),
    CONSTRAINT ck_quotations_deposits CHECK (required_deposit >= 0 AND deposit_received >= 0),
    CONSTRAINT ck_quotations_shortfall CHECK (deposit_shortfall = GREATEST(0, required_deposit - deposit_received)),
    CONSTRAINT ck_quotations_currency CHECK (currency = 'INR'),
    CONSTRAINT ck_quotations_validity CHECK (valid_until IS NULL OR issue_date IS NULL OR valid_until >= issue_date),
    CONSTRAINT ck_quotations_issued CHECK (
        status NOT IN ('ISSUED', 'SUPERSEDED')
        OR (issue_date IS NOT NULL AND valid_until IS NOT NULL AND issued_at IS NOT NULL AND issued_by_id IS NOT NULL))
);
CREATE UNIQUE INDEX ux_quotations_one_issued ON quotations (fleet_request_id) WHERE status = 'ISSUED';
CREATE INDEX ix_quotations_request ON quotations (fleet_request_id);
CREATE INDEX ix_quotations_status ON quotations (status);
CREATE INDEX ix_quotations_tax_rate ON quotations (tax_rate_id);
CREATE INDEX ix_quotations_issued_by ON quotations (issued_by_id);
CREATE INDEX ix_quotations_created_by ON quotations (created_by_id);

CREATE TABLE quotation_line_items (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quotation_id BIGINT         NOT NULL REFERENCES quotations (id) ON DELETE CASCADE,
    line_no      INTEGER        NOT NULL,
    variant_id   BIGINT         NOT NULL REFERENCES vehicle_variants (id),
    description  VARCHAR(255)   NOT NULL,
    quantity     INTEGER        NOT NULL,
    unit_price   NUMERIC(15, 2) NOT NULL,
    base_amount  NUMERIC(15, 2) NOT NULL,
    gst_rate     NUMERIC(5, 4)  NOT NULL,
    gst_amount   NUMERIC(15, 2) NOT NULL,
    line_total   NUMERIC(15, 2) NOT NULL,
    created_at   TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ    NOT NULL DEFAULT now(),
    version      BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT uq_quotation_line_items_line UNIQUE (quotation_id, line_no),
    CONSTRAINT ck_quotation_line_items_line_no CHECK (line_no > 0),
    CONSTRAINT ck_quotation_line_items_quantity CHECK (quantity > 0),
    CONSTRAINT ck_quotation_line_items_amounts CHECK (unit_price >= 0 AND base_amount >= 0 AND gst_amount >= 0),
    CONSTRAINT ck_quotation_line_items_gst_rate CHECK (gst_rate >= 0 AND gst_rate < 1),
    CONSTRAINT ck_quotation_line_items_total CHECK (line_total = base_amount + gst_amount)
);
CREATE INDEX ix_quotation_line_items_variant ON quotation_line_items (variant_id);

CREATE TABLE payment_receipts (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_number        VARCHAR(30)    NOT NULL,
    fleet_request_id      BIGINT         NOT NULL REFERENCES fleet_requests (id),
    quotation_id          BIGINT         REFERENCES quotations (id),
    receipt_type          VARCHAR(20)    NOT NULL,
    payment_method        VARCHAR(20)    NOT NULL,
    transaction_reference VARCHAR(100)   NOT NULL,
    amount                NUMERIC(15, 2) NOT NULL,
    received_date         DATE           NOT NULL,
    status                VARCHAR(20)    NOT NULL DEFAULT 'RECORDED',
    recorded_by_id        BIGINT         NOT NULL REFERENCES users (id),
    reviewed_by_id        BIGINT         REFERENCES users (id),
    reviewed_at           TIMESTAMPTZ,
    rejection_reason      VARCHAR(1000),
    created_at            TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at            TIMESTAMPTZ    NOT NULL DEFAULT now(),
    version               BIGINT         NOT NULL DEFAULT 0,
    CONSTRAINT uq_payment_receipts_number UNIQUE (receipt_number),
    CONSTRAINT ck_payment_receipts_amount CHECK (amount > 0),
    CONSTRAINT ck_payment_receipts_txn_ref CHECK (length(trim(transaction_reference)) > 0),
    CONSTRAINT ck_payment_receipts_type CHECK (receipt_type IN ('DEPOSIT', 'PAYMENT')),
    CONSTRAINT ck_payment_receipts_method CHECK (payment_method IN ('NEFT', 'RTGS', 'IMPS', 'UPI', 'CHEQUE', 'DEMAND_DRAFT')),
    CONSTRAINT ck_payment_receipts_status CHECK (status IN ('RECORDED', 'APPROVED', 'REJECTED')),
    CONSTRAINT ck_payment_receipts_reviewed CHECK (
        status = 'RECORDED' OR (reviewed_by_id IS NOT NULL AND reviewed_at IS NOT NULL)),
    CONSTRAINT ck_payment_receipts_rejection CHECK (status <> 'REJECTED' OR rejection_reason IS NOT NULL)
);
-- Duplicate-payment protection: the same reference can't be recorded twice, whatever the case or spacing.
CREATE UNIQUE INDEX ux_payment_receipts_txn_ref ON payment_receipts (upper(trim(transaction_reference)));
CREATE INDEX ix_payment_receipts_request ON payment_receipts (fleet_request_id);
CREATE INDEX ix_payment_receipts_quotation ON payment_receipts (quotation_id);
CREATE INDEX ix_payment_receipts_status ON payment_receipts (status);
CREATE INDEX ix_payment_receipts_recorded_by ON payment_receipts (recorded_by_id);
CREATE INDEX ix_payment_receipts_reviewed_by ON payment_receipts (reviewed_by_id);

CREATE TABLE production_orders (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    production_number    VARCHAR(30) NOT NULL,
    fleet_request_id     BIGINT      NOT NULL REFERENCES fleet_requests (id),
    plant_id             BIGINT      NOT NULL REFERENCES plants (id),
    variant_id           BIGINT      NOT NULL REFERENCES vehicle_variants (id),
    quantity             INTEGER     NOT NULL,
    scheduled_start      DATE        NOT NULL,
    estimated_completion DATE        NOT NULL,
    completed_at         TIMESTAMPTZ,
    status               VARCHAR(20) NOT NULL DEFAULT 'SCHEDULED',
    scheduled_by_id      BIGINT      NOT NULL REFERENCES users (id),
    notes                VARCHAR(1000),
    created_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT now(),
    version              BIGINT      NOT NULL DEFAULT 0,
    CONSTRAINT uq_production_orders_number UNIQUE (production_number),
    CONSTRAINT ck_production_orders_quantity CHECK (quantity > 0),
    CONSTRAINT ck_production_orders_dates CHECK (estimated_completion >= scheduled_start),
    CONSTRAINT ck_production_orders_status CHECK (status IN ('SCHEDULED', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT ck_production_orders_completed CHECK (status <> 'COMPLETED' OR completed_at IS NOT NULL)
);
CREATE INDEX ix_production_orders_request ON production_orders (fleet_request_id);
CREATE INDEX ix_production_orders_plant ON production_orders (plant_id);
CREATE INDEX ix_production_orders_variant ON production_orders (variant_id);
CREATE INDEX ix_production_orders_status ON production_orders (status);
CREATE INDEX ix_production_orders_scheduled_by ON production_orders (scheduled_by_id);

CREATE TABLE dispatches (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dispatch_number   VARCHAR(30)  NOT NULL,
    fleet_request_id  BIGINT       NOT NULL REFERENCES fleet_requests (id),
    from_location_id  BIGINT       REFERENCES inventory_locations (id),
    quantity          INTEGER      NOT NULL,
    scheduled_date    DATE         NOT NULL,
    dispatched_at     TIMESTAMPTZ,
    delivered_at      TIMESTAMPTZ,
    carrier           VARCHAR(150),
    vehicle_reference VARCHAR(100),
    status            VARCHAR(20)  NOT NULL DEFAULT 'SCHEDULED',
    scheduled_by_id   BIGINT       NOT NULL REFERENCES users (id),
    notes             VARCHAR(1000),
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version           BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uq_dispatches_number UNIQUE (dispatch_number),
    CONSTRAINT ck_dispatches_quantity CHECK (quantity > 0),
    CONSTRAINT ck_dispatches_status CHECK (status IN ('SCHEDULED', 'DISPATCHED', 'DELIVERED', 'CANCELLED')),
    CONSTRAINT ck_dispatches_dispatched CHECK (status NOT IN ('DISPATCHED', 'DELIVERED') OR dispatched_at IS NOT NULL),
    CONSTRAINT ck_dispatches_delivered CHECK (status <> 'DELIVERED' OR delivered_at IS NOT NULL),
    CONSTRAINT ck_dispatches_order CHECK (delivered_at IS NULL OR dispatched_at IS NULL OR delivered_at >= dispatched_at)
);
CREATE INDEX ix_dispatches_request ON dispatches (fleet_request_id);
CREATE INDEX ix_dispatches_location ON dispatches (from_location_id);
CREATE INDEX ix_dispatches_status ON dispatches (status);
CREATE INDEX ix_dispatches_scheduled_by ON dispatches (scheduled_by_id);
